#!/usr/bin/env node
/**
 * build.js — Office of Ordinary Hauntings
 *
 * Assembles the site's pages from two unserved folders:
 *
 *   sources/   one file per page: just that page's <main> content, preceded by
 *              a small front-matter comment.
 *   elements/  the shared pieces: layout.html (the page skeleton) and the
 *              partials it includes (header, ticker, menu, widgets, footer).
 *
 * The built pages are written to pages/, which the web server uses as its
 * document root (so URLs never include "pages"). They are committed, so a
 * plain `git pull` deploys the site. Assets (css/, js/, img/) stay at the repo
 * root and are referenced with root-absolute URLs such as /css/main.css.
 *
 * Source format:
 *
 *   <!--
 *   title: About the Office
 *   description: One sentence for search engines and link previews.
 *   -->
 *   <h2>...page content...</h2>
 *
 * Layout placeholders: {{title}}, {{description}}, {{content}}, and
 * {{> name}} to include elements/name.html (indented to match the placeholder).
 *
 * No dependencies; Node 18+ is enough.
 *
 * Usage: node scripts/build.js
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCES = path.join(ROOT, 'sources');
const ELEMENTS = path.join(ROOT, 'elements');
const PAGES = path.join(ROOT, 'pages');
const LAYOUT_FILE = 'layout.html';
const SITE_NAME = 'Office of Ordinary Hauntings';

/**
 * Split a page source into its front-matter fields and its content.
 *
 * @param {string} text Raw contents of a file in sources/.
 * @param {string} name File name, used only for error messages.
 * @returns {{meta: Object<string, string>, content: string}}
 * @throws {Error} If the front matter is missing or incomplete.
 */
function parseSource(text, name) {
  const match = text.match(/^<!--\s*\n([\s\S]*?)-->\s*\n?/);
  if (!match) {
    throw new Error(`${name}: missing front-matter comment at the top of the file`);
  }

  const meta = {};
  for (const line of match[1].split('\n')) {
    const colon = line.indexOf(':');
    if (colon > 0) {
      meta[line.slice(0, colon).trim()] = line.slice(colon + 1).trim();
    }
  }
  for (const key of ['title', 'description']) {
    if (!meta[key]) throw new Error(`${name}: front matter is missing "${key}"`);
  }

  return { meta, content: text.slice(match[0].length).replace(/\s+$/, '') };
}

/**
 * Expand every {{> name}} include in the layout with elements/name.html.
 * Each line of the partial takes the placeholder's indentation, so the built
 * HTML stays tidy to read.
 *
 * @param {string} layout Contents of elements/layout.html.
 * @returns {string} The layout with its partials inlined.
 * @throws {Error} If an included element does not exist.
 */
function expandIncludes(layout) {
  return layout.replace(/^([ \t]*)\{\{> ([\w-]+)\}\}[ \t]*$/gm, (_, indent, name) => {
    const file = path.join(ELEMENTS, `${name}.html`);
    if (!fs.existsSync(file)) {
      throw new Error(`layout.html: no element named "${name}" (expected elements/${name}.html)`);
    }
    return fs
      .readFileSync(file, 'utf8')
      .replace(/\s+$/, '')
      .split('\n')
      .map((line) => (line ? indent + line : line))
      .join('\n');
  });
}

/**
 * Build one page by dropping its content into the layout.
 *
 * @param {string} layout Contents of elements/layout.html, includes already expanded.
 * @param {string} file Source file name, e.g. "about.html".
 * @returns {string} The finished page.
 */
function buildPage(layout, file) {
  const { meta, content } = parseSource(fs.readFileSync(path.join(SOURCES, file), 'utf8'), file);

  // The home page is titled with the site name alone; the rest append it.
  const title = meta.title === SITE_NAME ? meta.title : `${meta.title} | ${SITE_NAME}`;

  // Replacer functions (not strings) so "$" in content is never treated as a pattern.
  let html = layout
    .replace('{{title}}', () => title)
    .replace('{{description}}', () => meta.description)
    .replace('{{content}}', () => `\n${content}\n`);

  // Flag the current page in the menu, for styling and screen readers.
  html = html.replace(`<li><a href="${file}">`, () => `<li><a href="${file}" aria-current="page">`);

  // Tell anyone who opens the output where it really comes from.
  html = html.replace(
    /^<!DOCTYPE html>\n/i,
    () => `<!DOCTYPE html>\n<!-- Generated by scripts/build.js from sources/${file}. Edit the source, not this file. -->\n`
  );

  if (html.includes('{{')) {
    throw new Error(`${file}: unreplaced {{placeholder}} in output`);
  }
  return html;
}

/** Build every page in sources/ (skipping files that start with "_"). */
function main() {
  const layout = expandIncludes(fs.readFileSync(path.join(ELEMENTS, LAYOUT_FILE), 'utf8'));
  const files = fs.readdirSync(SOURCES).filter((f) => f.endsWith('.html') && !f.startsWith('_'));
  fs.mkdirSync(PAGES, { recursive: true });

  for (const file of files) {
    fs.writeFileSync(path.join(PAGES, file), buildPage(layout, file));
    console.log(`built ${file}`);
  }
}

main();
